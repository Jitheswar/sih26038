function result = agreementCheckCases()
%AGREEMENTCHECKCASES What the §8.6 agreement check does at its boundaries.
%   RESULT = agreementCheckCases() runs grade.decisionPolicy over a small
%   set of hand-built cases and prints the decision and agreement state each
%   one reaches.  It loads no model, reads no image and needs no GPU, so it
%   answers questions about the check itself in seconds rather than in the
%   two hours a 550-image ablation pass costs.
%
%   It exists because two properties of the check are invisible in the
%   ablation table and hard to see in the source, and both change what the
%   pipeline does to a real patient:
%
%   1. The exact-level comparison.  When the rule engine can reach Level 2,
%      localAgreementStatus compares CNN level against rule level for exact
%      equality and calls any difference "insufficient evidence".  The
%      screening endpoint is binary (§11.2), so two channels that agree the
%      patient needs referral, and differ only on how severe the disease is,
%      are recorded as a failure to agree.
%
%   2. The capability cap is dropped on the way in.  icdrRule reports
%      maxReachableLevel, and with hard-exudate evidence only that ceiling
%      is 2.  normalizeDecisionInput collapses it to the boolean
%      referableLevelReachable (maxReachableLevel >= 2) and the check then
%      demands exact equality against a CNN that predicts up to Level 4.
%      Every CNN prediction of 3 or 4 is therefore an automatic mismatch:
%      the rule engine has no way to return those values.  icdrRule also
%      reports levelIsCapabilityCapped, which nothing reads.
%
%   The scenarios below are not a pass/fail test.  They are a printed
%   characterisation of current behaviour, kept so that a change to the
%   agreement check can be compared against what it replaced.

rng(42, 'twister');

% Six of the eight evidence fields have no detector when the learned channel
% is restricted to hard exudates, so they are capability gaps rather than
% case-level unknowns.  This mirrors what config/default.json's
% lesion_segmentation.evidence_heads produces at run time.
gaps = {'haemorrhageCountPerQuadrant', 'softExudateCount', ...
    'venousBeadingPerQuadrant', 'irmaPerQuadrant', 'neovascularisation', ...
    'vitreousOrPreretinalHaemorrhage'};

% Matches the frozen operating point recorded in config/default.json.
config = struct('decisionPolicy', struct( ...
    'referableThreshold', 0.70, 'autoClearThreshold', 0.40, ...
    'uncertaintyThreshold', 0.50, 'requireEvidenceForAutoClear', true, ...
    'alwaysEscalateLevel4', true, 'escalateOnUnknownEvidence', true, ...
    'escalateOnExplanationDisagreement', true, 'escalateOnCapabilityGap', false));

% The three policy variants the §11.6 ablations A10-A13 measure at scale.
% Printing them side by side here says what each one changes at the
% boundaries, which the ablation table cannot show because it reports totals.
variants = { ...
    'shipped (exact levels, spatial gate)',     true,  'exact'; ...
    'A10 (endpoint levels, spatial gate)',      true,  'endpoint'; ...
    'A11 (exact levels, spatial advisory)',     false, 'exact'; ...
    'A12 (endpoint levels, spatial advisory)',  false, 'endpoint'};

% description, cnnLevel, probability, ruleLevel, ruleReferable,
% maxReachableLevel, spatiallyAgree
scenarios = { ...
    'CNN 2 refer,  rule 2 refer,  levels equal',        2, 0.95, 2, true,  2, true; ...
    'CNN 3 refer,  rule 2 refer,  both say REFER',      3, 0.95, 2, true,  2, true; ...
    'CNN 4 refer,  rule 2 refer,  both say REFER',      4, 0.95, 2, true,  2, true; ...
    'CNN 0 clear,  rule 0 clear,  levels equal',        0, 0.05, 0, false, 2, true; ...
    'CNN 0 clear,  rule 1 clear,  both say CLEAR',      0, 0.05, 1, false, 2, true; ...
    'CNN 2 refer,  rule 2 refer,  spatial check fails', 2, 0.95, 2, true,  2, false; ...
    'CNN 0 clear,  rule 0 clear,  spatial check fails', 0, 0.05, 0, false, 2, false; ...
    'CNN 3 refer,  rule 1 capped below Level 2',        3, 0.95, 1, false, 1, true; ...
    'CNN 0 clear,  rule 1 capped below Level 2',        0, 0.05, 1, false, 1, true};

fprintf('\nAgreement check behaviour at the boundaries.\n');
fprintf('Referral gate %.2f, auto-clear gate %.2f.\n\n', ...
    config.decisionPolicy.referableThreshold, ...
    config.decisionPolicy.autoClearThreshold);

decisions = cell(size(scenarios, 1), size(variants, 1));
result = struct('scenario', {}, 'decisions', {});
for variantIndex = 1:size(variants, 1)
    variantConfig = config;
    variantConfig.decisionPolicy.escalateOnExplanationDisagreement = ...
        variants{variantIndex, 2};
    variantConfig.decisionPolicy.levelComparison = variants{variantIndex, 3};
    for index = 1:size(scenarios, 1)
        input = localInput(scenarios(index, :), gaps);
        policyResult = grade.decisionPolicy(input, variantConfig);
        decisions{index, variantIndex} = policyResult.decision;
    end
end

fprintf('%-48s |', 'scenario');
for variantIndex = 1:size(variants, 1)
    fprintf(' %-10s |', localShortName(variants{variantIndex, 1}));
end
fprintf('\n%s\n', repmat('-', 1, 48 + 13 * size(variants, 1)));
for index = 1:size(scenarios, 1)
    fprintf('%-48s |', scenarios{index, 1});
    for variantIndex = 1:size(variants, 1)
        fprintf(' %-10s |', decisions{index, variantIndex});
    end
    fprintf('\n');
    result(index).scenario = scenarios{index, 1}; %#ok<AGROW>
    result(index).decisions = decisions(index, :); %#ok<AGROW>
end

fprintf('\nColumns:\n');
for variantIndex = 1:size(variants, 1)
    fprintf('  %-10s  %s\n', localShortName(variants{variantIndex, 1}), ...
        variants{variantIndex, 1});
end

fprintf(['\nRows 2, 3 and 5 are the ones to look at.  In each the two ', ...
    'channels agree\non the referable/not-referable endpoint the system ', ...
    'exists to decide, and\nthe case still escalates because their exact ', ...
    'ICDR levels differ.\n']);
fprintf(['\nCompare row 2 against row 8.  They put the same CNN ', ...
    'prediction in front of\ntwo evidence channels and refer the patient ', ...
    'only when the channel is the\nweaker one.  A channel capped below ', ...
    'Level 2 cannot be compared, so the\ncheck skips the comparison and ', ...
    'the case proceeds; a channel that reaches\nLevel 2 is compared, ', ...
    'mismatches, and escalates.  Improving the evidence\nchannel ', ...
    'therefore lowers autonomous coverage on its own, which is the\n', ...
    'A5-versus-A9 result in §11.6 reproduced without a model or an ', ...
    'image.\n\n']);
end

function name = localShortName(label)
%LOCALSHORTNAME The leading token of a variant label, for a column heading.
parts = strsplit(label, ' ');
name = parts{1};
end

function input = localInput(scenario, gaps)
[~, cnnLevel, probability, ruleLevel, ruleReferable, maxReachable, ...
    spatiallyAgree] = scenario{:};

input = struct();
input.quality = struct('class', 'gradable', 'qualityClass', 'gradable', ...
    'enhancementApplied', false, 'metadata', struct( ...
        'enhancementApplied', false, ...
        'postEnhancementQualityClass', 'gradable'));
input.cnn = struct('predictedLevel', cnnLevel, ...
    'calibratedReferableProbability', probability, ...
    'classProbabilities', [], 'uncertaintyScore', [], ...
    'uncertaintyThreshold', []);
input.ruleEngine = struct( ...
    'icdrLevel', ruleLevel, 'level', ruleLevel, 'referable', ruleReferable, ...
    'escalationRecommendation', 'No escalation recommended.', ...
    'humanEscalationRecommended', false, 'uncertain', true, ...
    'caseUnknownEvidence', false, 'missingEvidenceFields', {gaps}, ...
    'capabilityGapFields', {gaps}, 'caseUnknownFields', {{}}, ...
    'maxReachableLevel', maxReachable, ...
    'referableLevelReachable', maxReachable >= 2, ...
    'evidenceSource', 'learned lesion segmentation, hard exudates only', ...
    'clinicalValidationStatus', ...
        'not clinically validated lesion segmentation');
input.explanation = struct( ...
    'gradCamMetadata', struct('available', true, ...
        'layer', 'activation_49_relu', 'rawResolution', [14, 14]), ...
    'lesionEvidenceMetadata', struct('candidateEvidence', true, ...
        'evidenceKnown', true, 'referable', ruleReferable), ...
    'gradCamAndLesionEvidenceSpatiallyAgree', spatiallyAgree, ...
    'lesionEvidenceSupportsCNN', true);
end
